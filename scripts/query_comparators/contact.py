"""Real ContactReader, hic-straw and official straw CLI query adapters.

Input files are generated by crates/hic/examples/round8_fixture.rs, with the
Juicer block layout, dummy chromosome All, and chr1/chr2 of 4 Mb each. This
module never creates inputs or executes measurements. Factory opens/caches
readers; query returns its complete native result unchanged. The coordinator
must normalize immediately after each query: reuse_out borrows one array.

Canonical matrix bytes are C-order little-endian float32. Pixel bytes are a
u64 count followed by uint32 row/column and float32 value columns. Traditional
sparse records are canonical stored-triangle cells; normalization expands cis
symmetry, clips the requested window, fixes trans orientation and sorts cells.
The independent fixture-rule oracle is precomputed outside timing. Every
normalizer checks it; canonical timing therefore includes a full bytes compare.
CLI matrix raw output remains sparse text and only normalization densifies it.
"""

from __future__ import annotations

import os
import random
import struct
import subprocess
from pathlib import Path

import numpy as np

# (requested row chromosome, requested column chromosome, row/column start
# bins, side in bins, units per bin, BP/FRAG). All windows are aligned.
Query = tuple[str, str, int, int, int, int, str]


def _queries(side: int, trans: bool) -> list[Query]:
    rng = random.Random(0x81C008 + side + 100_000 * trans)
    queries = []
    for i in range(8):
        x = rng.randrange(4000 - side + 1)
        if trans:
            # Includes the known stored cell (x, 17*x mod 4000), avoiding
            # empty-matrix special cases while retaining sparse trans tiles.
            y = min(x * 17 % 4000, 4000 - side)
            if i % 2:
                queries.append(("chr2", "chr1", y, x, side, 1000, "BP"))
            else:
                queries.append(("chr1", "chr2", x, y, side, 1000, "BP"))
        else:
            y = min(max(x + rng.randrange(-side // 4, side // 4 + 1), 0), 4000 - side)
            queries.append(("chr1", "chr1", x, y, side, 1000, "BP"))
    return queries


def _bounds(q: Query):
    a, b, row, col, side, resolution, unit = q
    flip = a > b
    x, y = (col, row) if flip else (row, col)
    return (
        min(a, b),
        max(a, b),
        x * resolution,
        (x + side) * resolution - 1,
        y * resolution,
        (y + side) * resolution - 1,
        flip,
    )


def _matrix_bytes(values) -> bytes:
    return np.asarray(values, dtype="<f4", order="C").tobytes(order="C")


def _pixel_bytes(rows, cols, values) -> bytes:
    return (
        struct.pack("<Q", len(rows))
        + np.asarray(rows, dtype="<u4").tobytes()
        + np.asarray(cols, dtype="<u4").tobytes()
        + np.asarray(values, dtype="<f4").tobytes()
    )


def _expected_matrix(q: Query):
    a, b, row, col, side, resolution, unit = q
    if unit == "FRAG":
        cells = (
            [(1, 1, 1.0), (2, 3, 3.0), (4, 4, 4.0), (5, 5, 8.0)]
            if a == b
            else [(1, 2, 3.0), (3, 4, 5.5), (5, 5, 7.0)]
        )
        stored = {}
        for x, y, value in cells:
            key = (x // resolution, y // resolution)
            stored[key] = np.float32(stored.get(key, 0.0) + np.float32(value))
        matrix = np.zeros((side, side), dtype="<f4")
        for (x, y), value in stored.items():
            points = {(x, y), (y, x)} if a == b else {(x, y)}
            for r, c in points:
                if row <= r < row + side and col <= c < col + side:
                    matrix[r - row, c - col] = value
        return matrix
    r = np.arange(row, row + side, dtype=np.int64)[:, None]
    c = np.arange(col, col + side, dtype=np.int64)[None, :]
    if a == b:
        x, y = np.minimum(r, c), np.maximum(r, c)
        present = (y - x < 48) & (y < 4000)
    else:
        x, y = (c, r) if a > b else (r, c)
        present = np.isin((y - 17 * x) % 4000, np.arange(12) * 31)
    matrix = np.where(present, ((x * 3 + y * 7) % 97 + 1) / 8.0, 0.0)
    return np.asarray(matrix, dtype="<f4")


def _oracle(queries, pixels: bool):
    expected = {}
    for q in queries:
        matrix = _expected_matrix(q)
        if pixels:
            rows, cols = np.nonzero(matrix)
            expected[q] = _pixel_bytes(
                (rows + q[2]) * q[5], (cols + q[3]) * q[5], matrix[rows, cols]
            )
        else:
            expected[q] = _matrix_bytes(matrix)
    return expected


def _checked(data: bytes, q, expected) -> bytes:
    if data != expected[q]:
        raise ValueError(f"contact payload differs from independent fixture oracle: {q!r}")
    return data


def _omics_pixels(raw, q: Query) -> bytes:
    rows, cols = np.asarray(raw.row), np.asarray(raw.col)
    values = np.asarray(raw.value)
    if not (len(rows) == len(cols) == len(values)):
        raise ValueError("pixel columns have different lengths")
    if np.any(~np.isfinite(values)) or np.any(values == 0):
        raise ValueError("Omics pixels must be finite and nonzero")
    if len(rows) > 1 and np.any(
        (rows[1:] < rows[:-1]) | ((rows[1:] == rows[:-1]) & (cols[1:] <= cols[:-1]))
    ):
        raise ValueError("Omics pixels must be sorted with unique positions")
    return _pixel_bytes(rows, cols, values)


def _record_rows(raw):
    if isinstance(raw, bytes):
        for line in raw.splitlines():
            if line.strip():
                fields = line.split()
                if len(fields) != 3:
                    raise ValueError(f"unexpected straw stdout row: {line!r}")
                yield int(fields[0]), int(fields[1]), float(fields[2])
    else:
        for record in raw:
            yield int(record.binX), int(record.binY), float(record.counts)


def _external_cells(raw, q: Query):
    a, b, row, col, side, resolution, unit = q
    first_row, last_row = row * resolution, (row + side) * resolution
    first_col, last_col = col * resolution, (col + side) * resolution
    cells = {}
    for x, y, value in _record_rows(raw):
        if not np.isfinite(value) or value == 0:
            continue
        points = {(x, y), (y, x)} if a == b else {(y, x) if a > b else (x, y)}
        for r, c in points:
            if first_row <= r < last_row and first_col <= c < last_col:
                if r % resolution or c % resolution:
                    raise ValueError("straw returned a non-aligned bin coordinate")
                if (r, c) in cells and cells[r, c] != np.float32(value):
                    raise ValueError("straw returned conflicting duplicate cells")
                cells[r, c] = np.float32(value)
    return cells


def _external_sparse(raw, q: Query, pixels: bool) -> bytes:
    cells = _external_cells(raw, q)
    if pixels:
        ordered = sorted(cells)
        return _pixel_bytes(
            [p[0] for p in ordered], [p[1] for p in ordered], [cells[p] for p in ordered]
        )
    matrix = np.zeros((q[4], q[4]), dtype="<f4")
    for (row, col), value in cells.items():
        matrix[row // q[5] - q[2], col // q[5] - q[3]] = value
    return _matrix_bytes(matrix)


def build_cases(ow, fixtures: Path, tools: dict) -> list[dict]:
    import hicstraw

    fixtures = Path(fixtures)
    required = [fixtures / f"round8-bp-v{v}.hic" for v in (8, 9)]
    required.append(fixtures / "round8-frag-v9.hic")
    for path in required:
        if not path.is_file():
            raise FileNotFoundError(path)
    straw = os.fspath(tools["straw"])

    def omics_factory(path, queries, expected, pixels, reuse):
        windows = {
            q: ow.types.ContactWindow(
                (q[0], q[2] * q[5], (q[2] + q[4]) * q[5]),
                (q[1], q[3] * q[5], (q[3] + q[4]) * q[5]),
                q[5],
                q[6],
            )
            for q in queries
        }

        def factory():
            reader = ow.query.ContactReader(path)
            out = np.empty((queries[0][4], queries[0][4]), dtype=np.float32) if reuse else None

            def query(q):
                return reader.pixels(windows[q]) if pixels else reader.matrix(windows[q], out=out)

            def normalize(raw, q):
                if pixels:
                    data = _omics_pixels(raw, q)
                else:
                    if raw.values.shape != (q[4], q[4]) or raw.values.dtype != np.float32:
                        raise ValueError("unexpected Omics matrix shape/dtype")
                    data = _matrix_bytes(raw.values)
                return _checked(data, q, expected)

            return {"query": query, "normalize": normalize, "close": reader.close, "reader": reader}

        return factory

    def python_factory(path, queries, expected, pixels):
        a, b, *_ = _bounds(queries[0])

        def factory():
            file = hicstraw.HiCFile(os.fspath(path))
            zoom = file.getMatrixZoomData(a, b, "observed", "NONE", "BP", 1000)
            state = [file, zoom]

            def query(q):
                _, _, x0, x1, y0, y1, _ = _bounds(q)
                method = state[1].getRecords if pixels else state[1].getRecordsAsMatrix
                return method(x0, x1, y0, y1)

            def normalize(raw, q):
                if pixels:
                    data = _external_sparse(raw, q, True)
                else:
                    matrix = np.asarray(raw)
                    if matrix.shape != (q[4], q[4]):
                        raise ValueError(f"hic-straw matrix shape {matrix.shape} != {(q[4], q[4])}")
                    data = _matrix_bytes(matrix.T if q[0] > q[1] else matrix)
                return _checked(data, q, expected)

            # hic-straw has no public explicit file-close method. Drop both
            # cached native objects; they must stay alive together until then.
            return {"query": query, "normalize": normalize, "close": state.clear}

        return factory

    def cli_factory(path, expected, pixels):
        def factory():
            def query(q):
                a, b, x0, x1, y0, y1, _ = _bounds(q)
                # Official main.cpp argc=8: matrixType, norm, file, both
                # closed-end regions, unit, binsize. stdout is three columns.
                argv = [
                    straw,
                    "observed",
                    "NONE",
                    os.fspath(path),
                    f"{a}:{x0}:{x1}",
                    f"{b}:{y0}:{y1}",
                    "BP",
                    "1000",
                ]
                return subprocess.run(argv, check=True, capture_output=True, timeout=30).stdout

            def normalize(raw, q):
                return _checked(_external_sparse(raw, q, pixels), q, expected)

            return {"query": query, "normalize": normalize, "close": lambda: None}

        return factory

    cases = []
    for version in (8, 9):
        path = fixtures / f"round8-bp-v{version}.hic"
        for trans in (False, True):
            pair = "trans" if trans else "cis"
            for side in (32, 256):
                queries = _queries(side, trans)
                for pixels in (False, True):
                    api = "pixels" if pixels else "matrix"
                    expected = _oracle(queries, pixels)
                    backends = [
                        {
                            "name": f"omics.{api}.allocate",
                            "kind": "omics",
                            "factory": omics_factory(path, queries, expected, pixels, False),
                            "note": "Raw ContactPixels uint32/uint32/float32 columns"
                            if pixels
                            else "Raw ContactMatrix with allocated C-order float32 array",
                        }
                    ]
                    if not pixels:
                        backends.append(
                            {
                                "name": "omics.matrix.reuse_out",
                                "kind": "omics",
                                "factory": omics_factory(path, queries, expected, False, True),
                                "note": "Raw ContactMatrix borrows one reused float32 array; normalize immediately",
                            }
                        )
                    backends.extend(
                        [
                            {
                                "name": f"hicstraw.{'getRecords' if pixels else 'getRecordsAsMatrix'}",
                                "kind": "python",
                                "factory": python_factory(path, queries, expected, pixels),
                                "note": "Raw contactRecord list in stored-triangle/block order"
                                if pixels
                                else "Raw NumPy array retains binding dtype; normalization casts float32 and fixes trans orientation",
                            },
                            {
                                "name": "straw",
                                "kind": "cli",
                                "factory": cli_factory(path, expected, pixels),
                                "note": "Raw sparse coordinate/count stdout bytes; subprocess and text materialization included; normalization expands cis and may build dense matrix",
                            },
                        ]
                    )
                    cases.append(
                        {
                            "id": f"contact.hic.v{version}.{pair}.{api}.bins{side}",
                            "interface": f"ContactReader.{api}",
                            "format": f"hic-v{version}",
                            "workload": f"8 fixed-seed aligned {side}x{side} bin {pair} queries; 1000 BP, raw observed NONE",
                            "queries": queries,
                            "backends": backends,
                            "metadata": {
                                "fixture": os.fspath(path),
                                "query_fields": [
                                    "row_chrom",
                                    "col_chrom",
                                    "row_bin",
                                    "col_bin",
                                    "side_bins",
                                    "resolution",
                                    "unit",
                                ],
                                "oracle": "Independent exact fixture formula; normalization compares complete bytes",
                                "trans_orientation": "alternates requested chr1/chr2 and chr2/chr1"
                                if trans
                                else "cis rectangular windows with mirrored triangle",
                                "out_lifetime": "until next query on that backend",
                            },
                        }
                    )

    frag_path = fixtures / "round8-frag-v9.hic"
    for resolution in (1, 2):
        for pixels in (False, True):
            queries = [
                (
                    "chr1",
                    "chr1" if i % 2 == 0 else "chr2",
                    0,
                    0,
                    6 // resolution,
                    resolution,
                    "FRAG",
                )
                for i in range(8)
            ]
            expected = _oracle(queries, pixels)
            api = "pixels" if pixels else "matrix"
            cases.append(
                {
                    "id": f"contact.hic.v9.frag.{api}.res{resolution}",
                    "interface": f"ContactReader.{api}",
                    "format": "hic-v9-FRAG",
                    "workload": "Correctness-only FRAG payload, fragment-index coordinates; no traditional baseline claimed",
                    "queries": queries,
                    "backends": [
                        {
                            "name": f"omics.{api}",
                            "kind": "omics",
                            "factory": omics_factory(frag_path, queries, expected, pixels, False),
                            "note": "FRAG indices, not base-pair coordinates; output bin-start positions",
                        }
                    ],
                    "metadata": {
                        "comparison": "N/A: traditional FRAG payload APIs not established in this harness",
                        "correctness_only": True,
                    },
                }
            )

    site_queries = ["chr1", "chr2"] * 4
    site_bytes = np.asarray([0, 17, 100, 700, 4_000_000], dtype="<u4").tobytes()

    def sites_factory():
        reader = ow.query.ContactReader(frag_path)

        def normalize(raw, q):
            if np.asarray(raw).dtype != np.uint32:
                raise ValueError("sites dtype must be uint32")
            data = np.asarray(raw, dtype="<u4").tobytes()
            if data != site_bytes:
                raise ValueError(f"sites differ from fixture positions: {q}")
            return data

        return {"query": reader.sites, "normalize": normalize, "close": reader.close}

    cases.append(
        {
            "id": "contact.hic.v9.sites",
            "interface": "ContactReader.sites",
            "format": "hic-v9-FRAG",
            "workload": "8 alternating-chromosome restriction-site reads, exact uint32 header positions",
            "queries": site_queries,
            "backends": [
                {
                    "name": "omics.sites",
                    "kind": "omics",
                    "factory": sites_factory,
                    "note": "Raw uint32 restriction-site position array",
                }
            ],
            "metadata": {
                "hicstraw": "N/A: no public restriction-site API established",
                "straw": "N/A: CLI has no sites query",
                "oracle": "Exact original restriction positions, not matrix output",
            },
        }
    )
    return cases
